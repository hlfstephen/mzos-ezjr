/* savkey.c — 存档身份：ROM 名 → 8.3 短名（纯哈希，零 I/O，编在 bank0）
 *
 * 要解决的问题：中文 ROM 在卡上的 8.3 短名是 GBK 字节硬截断。
 *   "口袋妖怪-水晶.gbc"   →  K 口 袋 妖 怪 (半个字)
 *   "口袋妖怪-皮卡丘.gbc" →  K 口 袋 妖 怪 (同样截断)
 * 两个完全不同的游戏算出**一模一样的名字**，于是存档互相覆盖、备份出同名
 * 文件、读档读回别人的进度。
 *
 * 解法：用**完整长名**算 28 位哈希，得到 "S1A2B3C4.SAV"。
 * 这是个纯函数 —— 同一个长名永远算出同一个短名，与创建顺序、目录里已有
 * 几个文件都无关（`~1/~2` 那种按序分配做不到：读侧不知道当初分到几号）。
 * 没有长名项的纯 8.3 ROM 用 8.3 名派生等效键兜底，读写两侧仍必相同。
 *
 * 为什么放在这里而不是 bank3：v0.15.0 把身份层整体搬进扩展 bank3，结果
 * 启动路径每次都要切 $2000；bank3 里的代码一旦碰到 $4000-$7FFF 窗口里的
 * FPGA 寄存器或 BANK1 函数就跳到别的字节上，真机表现为「按 A 卡死」。
 * 这里是纯计算，留在常驻区最安全，一个跳板都不需要。
 *
 * 输出为什么是字符串而不是 11 字节原始名：fatw.c 的 sav_name() 会把
 * "S1A2B3C4.SAV" 截到点、补 "SAV" 扩展名，正好还原成 11 字节原始项。
 * 所以这里给点分形式，fat_open_sav / fat_open_read 一行都不用改。
 */
#include <stdint.h>
#include "fat.h"

/* name83: 卡上的 8.3 名，"POKEMON.GBC"（大写，点分，可为空）
 * lfn:    ROM 完整长名（UCS-2），没有就传 0
 * out:    至少 13 字节，"S1A2B3C4.SAV" + NUL
 *
 * 28 位（7 个十六进制字符）配十几个存档文件，实际碰撞概率可以忽略；
 * 万一撞了也只是两个 ROM 共用一个档，不会破坏卡上别的数据。*/
void sav_ident(const char *name83, const uint16_t *lfn, char *out)
{
    uint32_t h = 0x811C9DC5UL;
    uint8_t  i, v;

    if (lfn && lfn[0]) {
        /* 33 倍写成「移位加」，不引 __mulslong（那是上百字节的库函数）。
         * 高低字节都混进去：中文长名的差异常常只在某一字节上。*/
        for (i = 0; i < FAT_LFN_FULL && lfn[i]; i++) {
            h = (h << 5) + h + (uint8_t)lfn[i];
            h ^= (uint8_t)(lfn[i] >> 8);
        }
    } else {
        /* 纯 8.3 ROM：没有长名项可查，用 8.3 名派生。读写两侧都走这里，
         * 所以仍然对得上；它的问题只是「不同中文 ROM 会撞」，而这一档
         * 本来就不存在那个问题（纯 8.3 名是唯一的）。*/
        for (i = 0; i < 8 && name83[i] && name83[i] != '.'; i++)
            h = (h << 5) + h + (uint8_t)name83[i];
    }

    out[0] = 'S';
    for (i = 0; i < 7; i++) {                /* 低 28 位 → 7 位大写 hex */
        v = (uint8_t)(h & 0x0F);
        out[1 + i] = (char)(v < 10 ? '0' + v : 'A' + v - 10);
        h >>= 4;
    }
    out[8]  = '.';
    out[9]  = 'S';
    out[10] = 'A';
    out[11] = 'V';
    out[12] = 0;
}
